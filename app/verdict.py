"""定性层：先把「正常 / 不正常」判断出来，再去谈条文和建议。

为什么单独一层
--------------
原来的流程是「检索 → 生成」，生成直接贴法条。用户问「公司不发工资正常吗」，
得到的回答是「根据劳动法第五十条规定：工资应当以货币形式……」。这是答非所问：
用户要一个判断，系统给了一段条文摘抄。

把定性抽出来有三个好处：
1. 它是 Agent 的一个决策步骤，可以出现在执行轨迹里（前端能看到「定性」这一步）；
2. 它能被单独检验——判断错了是定性错，不是措辞问题；
3. 生成器只负责把结论、依据、建议组织成人话，不再兼职做判断。

两种模式的分工
--------------
在线模式：由 LLM 读条文 + 案情做定性（真判断，见 llm.LLM.judge）
回放模式：用下面的规则表。规则表只覆盖种子语料里的条文，是**骨架演示**，
         不是能力上限。这点必须在文档里写清楚，不能拿它冒充模型能力。
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field

