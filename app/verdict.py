# 规则优先级。可主张型排在前面：「没签合同我能主张什么」，用户要的是
# 请求权基础（82 条），不是义务性规定（10 条）。
_KIND_ORDER = {"claimable": 0, "illegal": 1, "definition": 2, "legal": 3}


def _rules_for(question: str, evidences: list[Evidence]) -> list[_Rule]:
    """找出所有既有规则、又对得上用户描述的条款，按优先级排序。

    复数是有意的：「实习期不发工资」同时落在试用期工资（20 条）和工资支付
    义务（劳动法 50 条）上，只取一条就会漏掉另一半的救济路径。

    排序是「类型优先 + 触发词越具体越优先」：
    「没签合同满一年是不是变无固定期限」同时命中 82 条（触发词「没签」二字）
    和 14 条（触发词「无固定期限」五字），按字数排后者在前——用户问的是效力
    转换，不是二倍工资。只按规则表顺序排，最宽泛的规则永远赢。
    """
    by_id = {e.article_id: e for e in evidences}
    hits: list[tuple[int, _Rule]] = []
    for rule in active_rules():
        if rule.article_id not in by_id:
            continue
        matched = [t for t in rule.triggers if t in question]
        if not matched:
            continue
        # 命中话题词，但问的其实是这个话题下的另一件事（见 _Rule.not_triggers）。
        # 这里不是"降权"而是"跳过"：错定性比不定性强，答案是按 basis 写的。
        if any(t in question for t in rule.not_triggers):
            continue
        # 主词命中了，但还要有"动作词"才说明问的是这件事（见 needs_any）。
        if rule.needs_any and not any(t in question for t in rule.needs_any):
            continue
        hits.append((len(max(matched, key=len)), rule))
    hits.sort(key=lambda x: (-x[1].priority,
                             _KIND_ORDER.get(x[1].kind, 9), -x[0]))
    rules = [r for _, r in hits]

    # 问「期限/时效」的题，定性必须由时效那条主导。
    # 否则会被 claimable 的解除、欠薪规则抢走：m12「离职后申请仲裁的期限是多久，
    # 拖欠工资的情况有什么不同」的结论曾经在讲"以此为由解除合同并要求经济补偿"，
    # 问的是期限、答的是解除，而召回 1.0、要点 1.0——指标一点都看不出来。
    # 只在这条问法成立时才提权（时效词 + 仲裁/起诉词同时出现），
    # 因为"多久"也用于「工资多久发一次」「工伤多久内申请」这类不该归 27 条的问题。
    if _asks_limitation(question):
        for i, r in enumerate(rules):
            if r.article_id in _LIMITATION_ARTICLES:
                rules.insert(0, rules.pop(i))
                break

    # 问「口径」的题，让口径条文（definition）主导。
    # m10「加班费的计算基数是什么」原来先讲 44 条三档费率，基数那半句在「另外」；
    # r10「年终奖不发能不能去仲裁」先讲 50 条欠薪，受案范围在「另外」。两题结论
    # 不算错，但先答的不是问的那半。
    # 只在这样的问法成立时才提权，**不**动全局的 _KIND_ORDER——试过把 definition
    # 整体提一档，s17「休息日加班该给多少工资」立刻被 41 条的上限抢走，
    # 主集要点 100 → 95.3，那条路不通。
    if _asks_definitional(question):
        for i, r in enumerate(rules):
            if r.kind == "definition":
                rules.insert(0, rules.pop(i))
                break
    return rules


# 仲裁时效那一条。提权只认它：别的 procedure 类（受案范围、仲裁前置）
# 回答的不是"多久"。
_LIMITATION_ARTICLES = ("调解仲裁法_27",)

_LIMIT_WORDS = ("时效", "期限", "多久", "多长时间", "几个月", "几天", "几年")
_PROCEDURE_WORDS = ("仲裁", "起诉", "申诉", "打官司")


def _asks_limitation(question: str) -> bool:
    """问句是不是在问「多长时间内必须去仲裁/起诉」。"""
    return (any(k in question for k in _LIMIT_WORDS)
            and any(k in question for k in _PROCEDURE_WORDS))


# 问「口径/基数」「效力」「这事归不归仲裁管」的问法。共同点：问的是**规则本身**，
# 不是自己的请求权，所以答话该由 definition 型条文出。
_CALIBER_WORDS = ("基数", "口径", "标准是什么", "按什么算", "包不包括", "含不含")
_VALIDITY_WORDS = ("算不算", "有效吗", "还有效", "算数吗")
_SCOPE_WORDS = ("能不能去仲裁", "能不能申请仲裁", "可否仲裁", "受不受理",
                "归不归仲裁")


def _asks_definitional(question: str) -> bool:
    return any(k in question for k in
               _CALIBER_WORDS + _VALIDITY_WORDS + _SCOPE_WORDS)


def _rule_for(question: str, evidences: list[Evidence]) -> _Rule | None:
    """定性只认一条主规则，取规则表里排最前的那个。"""
    rules = _rules_for(question, evidences)
    return rules[0] if rules else None


def rule_by_article(article_id: str) -> _Rule | None:
    """按条号查规则。用于 lookup 题型：用户直接问某一条，不需要匹配触发词。

    同一条号可能有多条规则（通用 + 高频子情形，如 46 条有「七类情形」和
    「到期不续签」）。查原文时要用**基础规则**（priority 最低的那条）：
    用户问「第四十六条写了什么」，要看到的是那七类列举，
    而不是「到期不续签要给补偿」——后者只在场景匹配（_rules_for）里才该优先。
    两种用法各取所需，不能互相污染。
    """
    cands = [r for r in active_rules() if r.article_id == article_id]
    return min(cands, key=lambda r: r.priority) if cands else None


# 公开别名，生成层要用它判断「这个问题是不是跨了多条规范」。
rules_for = _rules_for


def cross_topic(question: str, evidences: list[Evidence]) -> bool:
    """一句话是不是同时问了两件不同的事。

    只看命中规则的条数会误判：「没签合同我能主张什么」同时命中第 10 条和
    第 82 条，但它们属于同一个主题（合同订立）的两个侧面，答案引一条就够。
    只有跨主题（合同 + 工资）才值得引两组依据。
    """
    return len({r.topic for r in _rules_for(question, evidences)}) > 1


