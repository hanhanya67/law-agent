# ---------------------------------------------------------------- 题型分类

_JUDGE_WORDS = ("正常吗", "正常么", "合法吗", "合法么", "违法吗", "可以吗",
                "算不算", "合理吗", "有没有问题", "对不对", "是否合法",
                "是否正常", "有效吗", "允许吗", "该不该", "能不能这样",
                "是不是违法", "有没有效")
_CLAIM_WORDS = ("能要什么", "要什么", "有什么权利", "能主张", "能拿什么",
                "有哪些赔偿", "可以要求", "能要求什么", "有什么补偿",
                "能要回", "应该给我", "有哪些")
_CALC_WORDS = ("多少", "几倍", "金额", "怎么算", "如何计算", "算一下",
               "赔多少", "能拿多少")
_PROC_WORDS = ("怎么办", "怎么处理", "流程", "去哪", "找谁", "投诉",
               "需要多久", "要多久", "怎么申请", "如何维权")
# 问的是「效力状态」而不是「条文内容」。带了条号也不能算 lookup——
# 「合同法第114条还有效吗」要的是废止判断，不是把原文抄一遍。
_EFFECT_WORDS = ("还有效", "仍然有效", "是否有效", "失效了", "废止了",
                 "作废", "还有用", "现在有效", "被替代", "还有没有效")


def classify_kind(question: str) -> str:
    """判断用户要的是哪一种答案。顺序即优先级。

    计算排在主张前面：「能拿多少」既是问金额也是问权利，但用户想要的是数字。
    """
    q = question.strip()
    if any(w in q for w in _EFFECT_WORDS):
        return "judge"
    if re.search(r"第[零一二三四五六七八九十百千\d]+条", q):
        # 提到条号 ≠ 只想看这一条。问「能不能按第 X 条」是在问**适用性**，
        # 正确答案常常落在另一条上：h12「劳动合同的违约金，能按民法典 585
        # 请求调低吗」——答案是不能套用 585，要用劳动合同法 25 条。
        # 判成 lookup 就等于把错的那条原文贴出去，还贴得理直气壮。
        #
        # 只认「能按 / 套用」这类明确的适用性问法，**不收回「适用」二字**：
        # v01/v03/v06 问的是「这条还有效吗 / 现在还适用吗」，那是效力核查，
        # lookup 分支里本来就处理得对（提示已废止 + 给替代条文），
        # 把「适用」也算进来会把这三道做对的题一起带偏。
        if any(w in q for w in ("能按", "能不能按", "可不可以按", "套用",
                                "是不是按", "该按哪")):
            return "judge"
        return "lookup"
    if any(w in q for w in _CALC_WORDS):
        return "calc"
    if any(w in q for w in _JUDGE_WORDS):
        return "judge"
    if any(w in q for w in _CLAIM_WORDS):
        return "claim"
    if any(w in q for w in _PROC_WORDS):
        return "procedure"
    # 陈述自身处境（"公司拖欠我工资"）默认按主张型处理：
    # 用户没说出口的那半句是「那我能怎么办」。
    return "claim"


