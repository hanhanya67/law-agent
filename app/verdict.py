    # 这条规则属于哪个主题。用途是判断「一句话是不是问了多件事」：
    # 「没签合同能主张什么」会同时命中第 10 条和第 82 条，但它们同属
    # contract 主题，只是义务和请求权两面，不该算跨主题、不该引两条依据。
    # 「没签合同还拖欠工资」命中 contract + wage，这才真的要引两条。
    topic: str = ""
    # 排他词：出现了这些词就**不算**命中，哪怕 triggers 里中了。
    #
    # 为什么需要：triggers 是按「话题」写的，但同一个话题下不同问法要不同条文。
    # 「加班」既可能问费率（44 条：150%/200%/300%），也可能问上限
    # （41 条：每日不超一小时、特殊原因三小时、每月三十六小时）——
    # 光看话题词分不开，结果是问上限的 h06 被 44 条当成欠薪案，答成
    # 「不正常，必须按 150% 支付」。答案里一个时长数字都没有。
    # 同理「经济补偿」可能问能不能给（46）、怎么算（47）、2008 年前要不要分段（97）。
    not_triggers: tuple[str, ...] = ()
    # 「同主题，但必须一起引」。
    #
    # judge_mock 补第二条依据的门槛是 `topic != 主规则.topic`，用来避免
    # 「没签合同能主张什么」把 10 条（签合同的义务）和 82 条（二倍工资）都摆出来
    # ——它们同属合同订立主题，说了等于重复。
    #
    # 但同主题不等于同内容。m04「公司以我不能胜任为由辞退，除了给补偿还要提前
    # 通知吗」同时问了两个义务：40 条（提前三十日通知／代通知金）和 46 条
    # （给经济补偿）。它们都是 termination 主题，按原逻辑只引 46 条，答案里
    # 一个「提前三十日」都没有——用户问的两半只答了一半。
    # 标了 co_cite 的规则就是「我这条不能只当背景」，命中了就得一起进依据。
    co_cite: bool = False
    # 「主词命中之外，还得有其中任意一个」。
    #
    # triggers 是纯子串匹配，中间夹字就断：「试用期被公司辞退」里没有
    # 「试用期被辞退」，也没有「试用期辞退」——而这类插入语（被公司/被单位/给）
    # 在口语里几乎必然出现。靠枚举变体是打地鼠：加完「被公司辞退」还有
    # 「被老板辞退」。真正要表达的是"两个词都在句子里"，顺序和间隔无所谓。
    #
    # m08 用它写成 triggers=("试用期",) + needs_any=("辞退","开除",...)：
    # 五个含「试用期」的题里，只有它同时含辞退类动词，其余四题照旧走 19/20 条。
    needs_any: tuple[str, ...] = ()
    # 显式优先级：数字大的先排。
    #
    # 什么时候需要它：同一个条号上有两条规则（通用 + 某个高频子情形），
    # 而「触发词越长越优先」这条默认规则会失效——通用规则常带口语长句
    # （「要给经济补偿」6 字），子情形规则反而是短词（「合同到期」4 字），
    # 于是问「到期不续签要不要给补偿」时又是通用规则先开口，
    # 答成「七类情形之一」让用户自己对号。
    # 用长度拼输赢是靠巧合，用数字表态才是明确意图。
    priority: int = 0


