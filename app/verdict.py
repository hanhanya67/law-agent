def advice_for(verdict: Verdict, question: str,
               evidences: list[Evidence]) -> list[str]:
    """给出可执行的建议，固定 4 条：核心动作 / 留什么证据 / 能多要多少 / 去哪多久。

    上限是硬的：建议超过 4 条，用户只会记住第一条。所以这里不是「有多少说多少」，
    而是「四个位置各放最有价值的那条」。通用建议永远不被截断——它回答的是
    「去哪、多久」，这是所有用户都会问的两个问题。
    """
    rules = _rules_for(question, evidences)
    if rules:
        core = list(rules[0].advice[:2])
        # 次规则只补一条，且不能和已有的重复
        if len(rules) > 1:
            for a in rules[1].advice:
                if not any(_similar(a, x) for x in core):
                    core.append(a)
                    break
    else:
        core = _profile_core_advice()

    # 除了原有权益，还有两笔「能多要的钱」，但只放一条：
    # 一条回答里塞三个赔偿项目会失焦，用户记不住。优先放金额更大的那个。
    #   二倍工资：最多 11 个月工资，通常远大于加付赔偿金
    #   加付赔偿金：应付金额的 50%–100%
    bonus: str | None = None
    if (any(e.article_id == "劳动合同法_82" for e in evidences)
            and any(t in question for t in ("合同", "签"))):
        bonus = ("自用工满一个月的次日起可主张二倍工资差额，最多十一个月"
                 "（《劳动合同法》第八十二条）")
    elif (rules and rules[0].article_id in _WAGE_RULES
            and verdict.kind in ("illegal", "claimable", "conditional")
            and any(e.article_id == "劳动合同法_85" for e in evidences)):
        bonus = ("经劳动行政部门责令限期支付仍不付的，可主张按应付金额 50%–100% "
                 "加付赔偿金（《劳动合同法》第八十五条）")
    if bonus:
        # 插在第 3 位而不是末尾：末尾会被 [:3] 截掉，而这条比「催告流程」更值钱。
        core.insert(2, bonus)

    return (core[:3] + [common_advice()])[:4]


