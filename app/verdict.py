def judge_mock(question: str, evidences: list[Evidence]) -> Verdict:
    """回放模式的定性。规则表打不到就诚实说无法判断，不猜。"""
    if not evidences:
        return Verdict(kind="unknown", label="现有资料无法判断",
                       reason="没有检索到可用于判断的条文")

    rules = _rules_for(question, evidences)
    if not rules:
        return Verdict(kind="unknown", label="无法给出确定判断",
                       reason="检索到的条文没有直接覆盖你描述的情形")
    rule = rules[0]
    v = Verdict(kind=rule.kind, label=rule.label, legal=rule.legal,
                reason=rule.reason,
                basis=[ev.cite() for ev in evidences
                       if ev.article_id == rule.article_id])
    if "实习期" in question and rule.article_id == "劳动合同法_20":
        v.kind = "conditional"
        v.label = "如果是入职后的试用期，这不正常"
        v.reason = _INTERN_REASON
    # 一句话问了两个违法点时（"没签合同还拖欠工资"），结论要把两件都点到。
    # 只说其中一件，用户会以为自己另一半的权益不存在。
    # 补一句必须来自**不同主题**的规则：「没签合同还拖欠工资」同时命中
    # 82 条（contract）和 10 条（contract），拼它们等于重复说同一件事；
    # 真正要说的是 50 条（wage）那半句——拖欠工资也违法。
    #
    # 三个入口，各自解决一种"只答了一半"：
    #   · 跨主题 —— 上面那种，一句话问了两件事；
    #   · co_cite —— 同主题但内容不同（m04：40 条通知 / 46 条补偿）；
    #   · definition 也放行 —— 原来只收 illegal/claimable，导致口径型条文
    #     （19 条试用期上限、调解仲裁法 27 时效）永远进不了结论段。
    #     实测 s15「只签试用期协议不签正式合同」只答了二倍工资，而「试用期
    #     不成立」才是他问的那半句；s18「在职被拖欠，时效怎么算」只答了欠薪
    #     违法，时效一句没有。两处都是补上 definition 之后才说全的。
    if len(rules) > 1:
        rest = rules[1:]
        # 「另外，…」这一句只有一处，先给**跨主题**那条：s18「在职被拖欠，
        # 时效怎么算」里，调解仲裁法 27 条的时效规则比 30 条原文值钱得多。
        sec = next((r for r in rest
                    if r.topic != rule.topic and not r.co_cite
                    and r.kind in ("illegal", "claimable", "definition")), None)
        # 没有跨主题的，才轮到 co_cite（m04 的 40 条与 46 条同属 termination，
        # 那条路走不通，但它问的"提前通知"必须说出来）。
        if sec is None:
            sec = next((r for r in rest
                        if r.co_cite
                        and r.kind in ("illegal", "claimable", "definition")), None)
        if sec:
            v.reason = f"{v.reason}；另外，{sec.reason}"
            v.basis = v.basis + [ev.cite() for ev in evidences
                                 if ev.article_id == sec.article_id]
        # co_cite 是「必引」而不是「占位」：没抢到那句话的，依据照样要摆出来。
        # 少了这一段，s18 拿到时效那句、却丢掉 30 条的「劳动报酬」原文——
        # 实测要点从 1.0 掉到 0.5，就是这么掉的。
        for r in rest:
            if r.co_cite and (sec is None or r.article_id != sec.article_id):
                extra = [ev.cite() for ev in evidences
                         if ev.article_id == r.article_id]
                v.basis = v.basis + [c for c in extra if c not in v.basis]
    return v


