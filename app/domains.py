BLANK = "＿＿＿＿"
DISCLAIMER = "仅供参考，不构成法律意见，不替代执业律师。"

# 「花了 200 块」「价款 89.9 元」这类才抽。「三倍」「第148条」「十倍」
# 都不带元/块，天然不会被误当成金额；中文数字（五百元）也进不来。
_MONEY = re.compile(r"(?:^|[^\d])(\d+(?:\.\d+)?)\s*(?:块钱|元|块)")

# 给前端 exDecision 用的空判例卡：结构完全照抄 cases.build_decision，
# 只是明确说「本内核没有本地判例库」，不把劳动争议案例串到消费/合同问题里。
_NO_CASES_NOTE = (
    "本内核暂无本地典型案例库，因此不列相似案件与结局分布；"
    "时间与费用见下方投入项。"
)


def _money_of(question: str) -> float | None:
    m = _MONEY.search(str(question or ""))
    if not m:
        return None
    try:
        v = float(m.group(1))
    except ValueError:
        return None
    # 0 元不是一笔真实交易；上限定在 1 亿，防止「123456789012 元」这种
    # 随口数字被当真，也避免金额大到界面上溢出。
    return v if 0 < v < 100_000_000 else None


def _fmt(v: float | None) -> str:
    if v is None:
        return BLANK
    return f"{v:g}"


def _scenario(label: str, formula: str, amount: float | None,
              basis: str, note: str) -> dict[str, Any]:
    return {"label": label, "formula": formula,
            "amount": amount, "amount_text": _fmt(amount),
            "basis": basis, "note": note}


