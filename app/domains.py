"""接入内核的专属能力层（v119）。纯规则、零网络、零模型，回放包里一样能跑。

为什么单独一个文件，而不是往 `extras.py` 里加 if：
`extras.py` 那五块是劳动争议专用，且 test_extras 用「恰好等于」钉死了
顶层键集合。最安全的做法是——劳动法内核**一个字都不动**，接入内核在
`extras` 出口处整包换成这里的同构数据。同构是关键：前端 exTimeline /
exClaims / exEvidence / exDecision / exPersona 不用改一行就能渲染。

「不同 RAG 不同功能」落在这两件事上，而不是换个提示词：
  · consumer  → 惩罚性赔偿测算（退一赔三 / 价款十倍，含保底）
  · civil     → 合同效力与违约金核查（含旧法废止衔接）
两者共用的三块（可主张项 / 举证清单 / 程序节点）也按领域整包换掉。

四条不许猜，和项目其它九处保持一致：
  1. 金额只从用户提问里的「N 元 / N 块」抽；抽不到就留 `＿＿＿＿`，
     绝不拿一个「大概差不多」的数去凑。
  2. 不给胜率、成功率、赢面，不建议是否起诉 / 索赔。
  3. 条件一律写成「若认定…则…」，不替用户认定欺诈或食品不合格。
  4. 条号必须是真实存在的条文；是全文还是摘录，note 里要说实话。
     现状：消保法 63 条、食安法 154 条、民法典 1260 条均已是官方全文，
     道路交通安全法只有 4 条摘录，工伤保险条例只有 6 条摘录。
"""
