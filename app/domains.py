def punitive_damages(question: str) -> dict[str, Any]:
    """消费/食安内核的专属能力：惩罚性赔偿测算。

    注意措辞：三倍和十倍都是**增加赔偿**，不是「一共能拿多少」。
    退还价款、赔偿实际损失是另外的请求权，不能混进同一个数字里——
    这正是普通人最容易算错、也最容易被自媒体带偏的地方。
    """
    q = str(question or "")
    price = _money_of(q)
    food = any(w in q for w in (
        "食品", "吃", "过期", "变质", "异物", "保质期", "生产日期", "标签",
        "说明书", "餐饮", "外卖", "奶粉", "保健食品", "不符合安全标准"))
    fraud = any(w in q for w in (
        "假货", "欺诈", "虚假宣传", "以次充好", "假冒", "翻新", "冒充",
        "骗", "虚标", "假的", "不是正品"))

    scenarios: list[dict[str, Any]] = []
    if food:
        ten = max(price * 10, 1000) if price is not None else None
        scenarios.append(_scenario(
            "价款十倍（食品安全法第 148 条）",
            "增加赔偿 = max（支付价款 × 10，1000 元）",
            ten, "《食品安全法》第一百四十八条",
            "也可以按实际损失的三倍主张，两者由消费者择一；"
            "标签、说明书存在不影响食品安全且不会误导的瑕疵时，不适用这一条。" ))
        scenarios.append(_scenario(
            "损失三倍（同一条的另一档）",
            "增加赔偿 = 实际损失 × 3",
            None, "《食品安全法》第一百四十八条",
            "损失金额须凭医疗票据、误工证明等材料核算。" ))
    if fraud or not food:
        triple = max(price * 3, 500) if price is not None else None
        scenarios.append(_scenario(
            "增加赔偿三倍（消费者权益保护法第 55 条）",
            "增加赔偿 = max（价款或服务费用 × 3，500 元）",
            triple, "《消费者权益保护法》第五十五条",
            "前提是经营者有欺诈行为并被认定；退还价款是另一项请求，"
            "不在这个三倍数字里。" ))

    if price is None:
        note = ("提问里没有可识别的实际支付金额，这里只给计算式、不给数字。"
                "请填入小票或订单上的金额。")
    else:
        note = (f"按提问里读到的价款 {_fmt(price)} 元代入上式。"
                "这是法条规定的计算式，不是对个案结果的预测；"
                "是否构成欺诈、食品是否不符合安全标准，须由有权机关认定。")

    return {
        "available": True,
        "id": "punitive_damages",
        "title": "惩罚性赔偿测算",
        "summary": ("把「退一赔三」「十倍赔偿」拆成法条上的计算式："
                    "三倍/十倍是增加赔偿，保底 500 / 1000 元，"
                    "退款与实际损失另算。"),
        "price_read": price,
        "price_blank": BLANK if price is None else None,
        "scenarios": scenarios,
        "conditions": [
            "商品或服务是否存在欺诈行为 / 食品是否不符合食品安全标准，"
            "是适用惩罚性赔偿的前提，须由证据认定",
            "消费者需持有购买凭证；经营者明知缺陷仍提供的，另有加重情形",
            "食品标签、说明书的不影响安全且不误导的瑕疵属于法定除外情形",
        ],
        "basis": ["《消费者权益保护法》第五十五条",
                  "《食品安全法》第一百四十八条"],
        "note": note,
        "disclaimer": DISCLAIMER,
        "no_win_rate": "不提供胜率、成功率或「建议索赔」结论。",
        "no_guess": "没有实际支付金额时金额一律留空，不估算。",
    }


