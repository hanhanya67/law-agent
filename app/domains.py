def contract_check(question: str) -> dict[str, Any]:
    """民法典·合同内核的专属能力：效力、违约金、时效与新旧法衔接核查。

    这里复用了项目最早的杀手级演示场景：原《合同法》第 114 条已随
    《民法典》2021-01-01 施行废止，正解是第 585 条。换个内核也能讲
    「版本感知」，正好证明这套能力属于引擎、不属于某一部法。
    """
    q = str(question or "")
    items: list[dict[str, Any]] = []

    def add(i: str, label: str, basis: str, rule: str, hit: bool) -> None:
        items.append({"id": i, "label": label, "basis": basis,
                      "rule": rule, "status": "需要核对",
                      "hit": hit, "quote": ""})

    asks_version = any(w in q for w in ("还有效", "失效", "废止", "替代", "旧条",
                                        "114", "合同法", "现在还能", "被哪部"))
    asks_penalty = any(w in q for w in ("违约金", "过高", "过低", "调整", "赔偿数额"))
    asks_effect = any(w in q for w in ("有效吗", "无效", "效力", "能撤销", "算不算合同"))
    asks_limit = any(w in q for w in ("时效", "多久", "过期", "还能不能告", "超过三年"))
    asks_boiler = any(w in q for w in ("格式条款", "霸王条款", "免责条款", "默认勾选"))

    # 一个都没命中时，把五项都列成「需要核对」，不假装读懂了问题。
    show_all = not any((asks_version, asks_penalty, asks_effect,
                        asks_limit, asks_boiler))

    if asks_version or show_all:
        add("version", "新旧法衔接", "《民法典》第五百八十五条",
            "原《合同法》第一百一十四条已随《民法典》2021-01-01 施行废止；"
            "违约金规则现见《民法典》第五百八十五条，不要再引旧条号。",
            asks_version)
    if asks_penalty or show_all:
        add("penalty", "违约金调整", "《民法典》第五百八十五条第二款",
            "约定的违约金低于造成的损失的，可以请求增加；"
            "过分高于造成的损失的，可以请求适当减少。是否「过分高于」须结合"
            "实际损失、履行情况与过错程度判断；倍数由裁判机关裁量。",
            asks_penalty)
    if asks_effect or show_all:
        add("effect", "民事法律行为效力", "《民法典》第一百四十三条、第一百五十三条",
            "看行为人是否有相应能力、意思表示是否真实、"
            "是否违反强制性规定或公序良俗；须结合完整条款判断。",
            asks_effect)
    if asks_limit or show_all:
        add("limitation", "诉讼时效", "《民法典》第一百八十八条",
            "一般诉讼时效为三年，自权利人知道或应当知道权利受损及义务人之日起算；"
            "起算日按具体事实确定。",
            asks_limit)
    if asks_boiler or show_all:
        add("boilerplate", "格式条款", "《民法典》第四百九十六条、第四百九十七条",
            "提供格式条款一方须提示说明与对方有重大利害关系的条款；"
            "不合理免除自身责任、加重对方责任、限制对方主要权利的条款可能无效。",
            asks_boiler)

    return {
        "available": True,
        "id": "contract_check",
        "title": "合同效力与违约金核查",
        "summary": ("把一句口语问题拆成可逐项核对的法定要件：效力、违约金、"
                    "诉讼时效、格式条款，外加新旧法条号衔接。"),
        "items": items,
        "conditions": [
            "核查项是「要核对什么」，不是对合同效力的判断结论",
            "违约金是否过高须以实际损失为基础，不能只按约定比例下结论",
            "旧条号检索到已废止条文时，必须提示被哪部法替代",
        ],
        "basis": ["《民法典》第一百四十三条", "《民法典》第一百五十三条",
                  "《民法典》第一百八十八条", "《民法典》第四百九十六条",
                  "《民法典》第五百八十五条"],
        "note": ("只列法定要件与条号；所引条文为全文，可逐条核对，"
                 "正式引用以官方文本为准。"),
        "disclaimer": DISCLAIMER,
        "no_win_rate": "不提供胜率、成功率或「建议起诉」结论。",
        "no_guess": "不代为认定合同效力，也不推算具体违约金金额。",
    }


