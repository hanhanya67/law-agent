def system(name: str, profile=None) -> str:
    """按内核取提示词。

    `profile=None` 表示读当前会话内核（contextvar），不是「强制劳动法」——
    chat 的 worker 线程里 `with profiles.use(pid):` 一包，下面所有
    `system("XXX")` 就自动跟着换，调用方一处都不用改。
    劳动法内核或没登记的常量名一律返回原常量，保证 v118 逐字不变。
    """
    from . import profiles as _profiles
    p = _profiles.get() if profile is None else _profiles.resolve(profile)
    if p.id == "labor":
        return globals().get(name, "")
    fn = _DOMAIN_SYSTEMS.get(name)
    if fn is None:
        # VERIFY / DECISION_USER 本身是领域无关的，原样复用。
        # ASK_SYSTEM 自 v135 起已按内核注册（_domain_ask），不再走这里。
        # VISION_SYSTEM 是劳动争议图片专用，服务端在非劳动法内核下
        # 会直接关掉图片证据录入，不会把这段提示词发出去。
        return globals().get(name, "")
    return fn(p)

