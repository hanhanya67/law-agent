# -*- coding: utf-8 -*-
"""
等义条文表：同一件事的并行规定。

为什么需要这张表：
  劳动合同法第四十二条列举「用人单位不得解除劳动合同」的情形，其中第四项是
  「女职工在孕期、产期、哺乳期的」。而《劳动法》第二十九条的写法**一模一样**——
  同一种列举结构、同一项内容，只是因为劳动法管的是第二十六、二十七条的解除，
  劳动合同法管的是第四十、四十一条。

  用户问「我怀孕了公司能辞退我吗」，任何一条都能回答，而且两条都没有废止。
  但 gold 只标了一条，于是模型引了另一条就被判「漏召」。这不是模型的缺陷，
  是标注时只标了一条的简化。

设计取舍：
  · **不改 gold**。gold 记录的是「出题人当时认为最核心的那一条」，这是历史事实，
    改了就没法追溯题目变过没有。
  · 等义关系单独声明在这里，判定时「命中任一即算命中」。要撤销只需删一行，
    不影响题库本身。
  · 只收**逐项内容对得上**的条目。不是「相关」，是「换成另一条结论不变」。
    宁可少收，不可乱收——这张表每加一条，都是在放松判定。

用法（run_eval.py / recompute.py 共用）：
    hit = set(gold) & got
    hit |= {g for g in gold if g not in hit
            and any(e in got for e in EQUIV.get(g, ()))}
"""
from __future__ import annotations

# 键与值都是条文 id，双向登记（任一方向命中都算）
EQUIV: dict[str, tuple[str, ...]] = {
    # 怀孕/患病/工伤期间不得解除——两条列举逐项对应
    "劳动合同法_42": ("劳动法_29",),
    "劳动法_29": ("劳动合同法_42",),
    # 工资应当按时足额支付——30 条多一句「可申请支付令」，不影响「该不该发」这个结论
    "劳动合同法_30": ("劳动法_50",),
    "劳动法_50": ("劳动合同法_30",),
    # 劳动争议先裁后审——5 条讲程序，79 条讲同一套程序还有调解前置
    "调解仲裁法_5": ("劳动法_79",),
    "劳动法_79": ("调解仲裁法_5",),
}


def expand_gold(gold: list[str], got: set[str]) -> set[str]:
    """把 gold 里「已被等义条文覆盖」的那几条也算成命中。"""
    if not gold:
        return set()
    hit = set(gold) & got
    for g in gold:
        if g in hit:
            continue
        if any(e in got for e in EQUIV.get(g, ())):
            hit.add(g)
    return hit
