    ok("m03 仍走七类情形那条", "七类情形" in head_m03, head_m03[:40])

    print("\n[26] 越界闸门扩到租房/借贷/消费；年限折算；85 条加付赔偿金")
    # 第三套探针（eval/_probe_scope.jsonl）撞出的三类问题，锁成回归。
