    ok("3年7个月 → (3,7)", service_months("被辞退，经济补偿金怎么算，我干了3年7个月") == (3, 7),
       service_months("被辞退，经济补偿金怎么算，我干了3年7个月"))
    ok("3年7个月 → 4 个月工资", compensation_months(3, 7)[0] == 4,
       compensation_months(3, 7))
    ok("一年零三个月 → 1.5 个月", compensation_months(1, 3)[0] == 1.5,
       compensation_months(1, 3))
    # ③ 85 条加付赔偿金：欠薪 + 问赔偿金才落到这里；经济补偿/违法解除不能抢过去。
    ids_n08 = rule_ids("公司拖欠工资，我能要多少赔偿金",
                       ["劳动合同法_85", "劳动合同法_30"])
    ok("n08 欠薪问赔偿金落到 85 条", "劳动合同法_85" in ids_n08, ids_n08)
    ids_n05 = rule_ids("被辞退，经济补偿金怎么算，我干了3年7个月",
                       ["劳动合同法_85", "劳动合同法_47"])
    ok("n05 经济补偿不被 85 条抢走", "劳动合同法_85" not in ids_n05, ids_n05)

    print("\n[27] v81：补《工伤保险条例》语料后的定性规则")
    # 六条语料（17/20/33/37/62/64）入库后，规则层原来一条都没命中，
    # 导致 n06/r07 答成经济补偿、e09 被判 unknown。下面三条规则要把题接住。
    # ① r07：工伤十级赔偿 → 37 条，结论讲"十级 7 个月本人工资"。
    v_r07 = verdict.judge_mock("工伤十级伤残大概能赔多少钱",
                               [_ev("工伤保险条例_37")])
    ok("r07 定性落第三十七条", v_r07.legal == "适用《工伤保险条例》第三十七条",
       v_r07.legal)
    ok("r07 结论含「7个月」", "7个月" in v_r07.head(), v_r07.head()[:80])
    ok("r07 依据含第三十七条",
       any("第三十七条" in b for b in v_r07.basis), v_r07.basis)
    # ② n06：工伤十级补助金是几个月工资 → 37 条，即便证据里同时有 47 条。
    v_n06 = verdict.judge_mock(
        "工伤十级一次性伤残补助金是几个月工资",
        [_ev("工伤保险条例_37"), _ev("劳动合同法_47")])
    ok("n06 主依据仍是 37 条（不被经济补偿抢走首句）",
       "工伤保险条例_37" in rule_ids(
           "工伤十级一次性伤残补助金是几个月工资",
           ["工伤保险条例_37", "劳动合同法_47"]),
       rule_ids("工伤十级一次性伤残补助金是几个月工资",
                ["工伤保险条例_37", "劳动合同法_47"]))
    ok("n06 结论含「7个月」", "7个月" in v_n06.head(), v_n06.head()[:90])
    ok("n06 不被补一句经济补偿（同 termination 主题抑制「另外」）",
       "经济补偿" not in v_n06.head(), v_n06.head()[:90])
    # ③ e09：工伤认定一般要多久 → 20 条（60日/15日），改写层已分流不走仲裁时效。
    v_e09 = verdict.judge_mock("工伤认定一般要多久出结果",
                               [_ev("工伤保险条例_20")])
