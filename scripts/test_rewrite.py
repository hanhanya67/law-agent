    #    改成语义配对「谁在收」才分得开；n03 离婚是原来的基准，不能回退。
    ok("n01 房东不退押金判越界", _guess_intent("房东不退押金怎么办") == "out_of_scope",
       _guess_intent("房东不退押金怎么办"))
    ok("n01 租房押金也判越界", _guess_intent("租房的押金房东不肯退") == "out_of_scope",
       _guess_intent("租房的押金房东不肯退"))
    ok("n03 离婚仍判越界（基准）", _guess_intent("离婚的时候房子怎么分") == "out_of_scope",
       _guess_intent("离婚的时候房子怎么分"))
