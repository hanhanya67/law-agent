    # priority=1，靠显式表态压过去，不跟它比长度。
    head_h05 = verdict.judge_mock("劳动合同到期了公司不续签，要给经济补偿吗",
                                  [_ev("劳动合同法_46"), _ev("劳动合同法_47")]).head()
