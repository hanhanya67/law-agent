PASS, FAIL = [], []


def ok(name: str, cond: bool, detail: object = "") -> None:
    (PASS if cond else FAIL).append(name)
    print(f"  [{'PASS' if cond else 'FAIL'}] {name}"
          + (f"  → {detail}" if detail != "" else ""))


def recall(idx: LawIndex, qs: list[str], topk: int = 8) -> set[str]:
    """把若干路检索式各搜一遍，合并成证据集合（模拟多路合并去重）。"""
    got: set[str] = set()
    for s in qs:
        got |= {h[1]["id"] for h in idx.search(s, topk=topk)}
    return got


def law_of(q: str) -> str:
    """复刻 _mock_decide 的取法名路径：定位第一个条号，再问它属于哪部法。

    这里刻意用和生产代码同一个正则，而不是手写 index()——否则测试保护的是
    「翻译后的位置」，代码改了正则它还是绿的。
    """
    m = re.search(r"第([零一二三四五六七八九十百千\d]+)条", q)
    if not m:
        raise AssertionError(f"用例里没有条号：{q}")
    return _law_near_article(q, m.start())


