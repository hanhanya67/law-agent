def main() -> int:
    idx = LawIndex(CORPUS_PATH)

    def _ev(aid: str) -> Evidence:
        """按 id 造一条最简证据。_rules_for 只要求 article_id 在证据里。"""
        a = idx.by_id[aid]
        return Evidence(article_id=a["id"], law_name=a["law_name"],
                        article_no=a["article_no"],
                        article_no_cn=a["article_no_cn"],
                        content=a["content"], score=0.0, source="direct",
                        # 语料里的失效状态要带过来，否则测「部分失效」时
                        # 每条证据都是「现行有效」，测的是个假的。
                        status=a.get("status", "现行有效"),
                        repealed_note=a.get("repealed_note", ""))

    print("\n[1] 口语说法要被改写成条文措辞，并且真的召回得到")
    for q, term, gold in CASES:
        qs = _rewrite_queries(q)
        ok(f"「{q}」改写含「{term}」", any(term in x for x in qs), qs)
        got = recall(idx, qs)
        ok(f"「{q}」能召回 {gold}", gold in got,
           "、".join(sorted(got))[:60] or "证据集为空")

    print("\n[2] 已经是术语的问法不该被改写带偏")
    for q, bad, gold in MUST_NOT:
        qs = _rewrite_queries(q)
        ok(f"「{q}」不含「{bad}」", all(bad not in x for x in qs), qs)
        ok(f"「{q}」仍能召回 {gold}", gold in recall(idx, qs))

    print("\n[3] 短句：能映射到术语就照常检索，映射不出才算信息不足")
    # c08 只有 7 个字，被 len<8 判成 clarify 时，证据集整个是空的
    ok("「试工期能定多长」按咨询处理（7 个字也是完整问题）",
       _guess_intent("试工期能定多长") == "case_consult",
       _guess_intent("试工期能定多长"))
    for q in ("你好", "在吗", "嗯"):
        ok(f"「{q}」仍按信息不足处理", _guess_intent(q) == "clarify", _guess_intent(q))

    print("\n[4] 计划该不该被执行：多路必跑，单路只在「查条号 + 真改写」时跑")
    # 这条判断踩过两次坑，方向相反：
    #   写死 >1  → h12 的计划（单条、但正是那条改写）永远不执行，recall 0
    #   改写成 >=1 → v01/v06 拿原句去搜，噪音挤掉替代条文，主集掉 1.2 点
    # 所以四个组合都要钉，缺一个就会有人往任意一边"简化"。
    q_h12 = "劳动合同里约定的违约金，能按民法典第五百八十五条请求调低吗"
    ok("多路计划一律执行",
       should_run_plan(["甲", "乙"], "原句", "case_consult"))
    ok("单路原句 + 普通提问 → 交给兜底，不抢预算",
       not should_run_plan(["原句"], "原句", "case_consult"))
    ok("单路改写 + 查条号 → 必须执行（h12 缺的就是这一步）",
       should_run_plan(["除本法第二十二条和第二十三条规定的情形外 不得约定违约金"],
                       q_h12, "statute_lookup"))
    ok("单路原句 + 查条号 → 不执行（v01/v06 靠精确取条 + 效力核查）",
       not should_run_plan([q_h12], q_h12, "statute_lookup"))

    print("\n[5] 越界判定：法律内部、但不在劳动法里的领域也要拦")
    # 早先只拦「天气/股票/写代码」这种完全不沾边的词，刑事、婚姻、侵权全放过去，
    # 再被字面巧合的条文硬答：h14「职务侵占会被判刑吗」拿民法典 847
    # （职务技术成果）当依据，r03「离婚房子怎么分」拿劳动法 18（劳动合同无效）
    # 当依据——格式正确、条号真实、完全答非所问，比直接拒答更危险。
    for q in ("公司说我职务侵占已经报警了，我会被判刑吗",      # h14
              "离婚的时候房子怎么分",                          # r03
              "被邻居家的狗咬了，怎么索赔",                    # r04
              "公司食堂的饭菜太难吃了，我能起诉公司吗"):       # r01
        ok(f"「{q[:14]}…」判越界", _guess_intent(q) == "out_of_scope",
           _guess_intent(q))
    # 反例比正例重要：同一个词换个语境就是正经劳动法问题。
    # 「狗」单独不能拦——公司养的狗咬伤员工是工伤；「食堂」单独不能拦——
    # 食堂饭钱从工资里扣是工资问题。所以这类走"两词同时出现"的组合判断。
    for q in ("公司养的狗把我咬伤了，算工伤吗",
              "公司食堂的饭钱从工资里扣，合法吗",
              "公司把我派到外地常驻，来回的路费应该谁出"):   # h13 在范围内，只是库里缺
        ok(f"「{q[:14]}…」不算越界", _guess_intent(q) != "out_of_scope",
           _guess_intent(q))

    print("\n[6] 定性规则：话题词相同，焦点不同必须落到不同条文")
    # 这一节的坑和 [5] 是一类的反面：那里是"该拦的没拦"，这里是"该分的没分"。
    # 规则表按**话题**写触发词，但同一话题下不同问法要不同条文，
    # 光看话题词分不开，于是答案引了对的条文号码、讲了错的事。
    def rule_ids(q: str, aids: list[str]) -> list[str]:
        evs = [_ev(a) for a in aids]
        return [r.article_id for r in verdict._rules_for(q, evs)]

    # 加班：上限（41）vs 费率（44）。两条都在证据里，靠 not_triggers 分开。
    ok("问加班上限不再被判成欠薪案（不命中 44 条）",
       "劳动法_44" not in rule_ids("公司安排我加班，每天最多能加几个小时",
                                   ["劳动法_41", "劳动法_44"]),
       rule_ids("公司安排我加班，每天最多能加几个小时",
                ["劳动法_41", "劳动法_44"]))
    ok("问加班费率仍命中 44 条（收窄没伤到正向）",
       "劳动法_44" in rule_ids("休息日安排我加班又不给补休，应该给多少工资",
                               ["劳动法_41", "劳动法_44"]))
    # 经济补偿：折算标准（47）vs 2008 年前分段（97）
    ok("问 2008 年前分段不再被 47 条抢走",
       "劳动合同法_47" not in rule_ids(
           "劳动合同法2008年施行前入职的老员工，经济补偿要分段算吗",
           ["劳动合同法_47", "劳动合同法_97"]))
    ok("问补偿标准仍命中 47 条",
       "劳动合同法_47" in rule_ids("经济补偿按什么标准算",
                                   ["劳动合同法_47", "劳动合同法_97"]))
    # 工资：月付义务（劳动法 50）vs 跳过仲裁直接起诉（程序）
    ok("问能不能不仲裁直接起诉，不再被 50 条当成欠薪案",
       "劳动法_50" not in rule_ids(
           "公司拖欠工资，我可以不经过仲裁直接去法院起诉吗",
           ["劳动法_50", "调解仲裁法_5"]))
    ok("问拖欠工资仍命中 50 条",
       "劳动法_50" in rule_ids("公司拖欠工资三个月了", ["劳动法_50", "调解仲裁法_5"]))
    # 新增的三条规则：以前这些题无规则命中，主依据退化成检索第一条。
    ok("问提前三十天通知落到 40 条",
       "劳动合同法_40" in rule_ids(
           "公司没提前三十天通知就直接辞退我，要多给一个月工资吗",
           ["劳动合同法_40", "实施条例_20"]))
    ok("问能不能不仲裁直接起诉落到调解仲裁法 5 条",
       "调解仲裁法_5" in rule_ids(
           "公司拖欠工资，我可以不经过仲裁直接去法院起诉吗",
           ["劳动法_50", "调解仲裁法_5"]))
    ok("劳动合同违约金落到 25 条，且不套用民法典",
       "劳动合同法_25" in rule_ids(
           "劳动合同里约定的违约金，能按民法典第五百八十五条请求调低吗",
           ["劳动合同法_25", "民法典_585"]))
    # 38 条现在有两条规则（社保被迫离职 / 欠薪被迫解除）。同一 article_id
    # 允许多条规则并存，靠触发词区分，别让后加的那条吞掉原来的。
    ok("欠薪被迫解除落到 38 条",
       "劳动合同法_38" in rule_ids(
           "公司拖欠工资，我能不能以此为由解除合同并要求补偿",
           ["劳动合同法_30", "劳动合同法_38", "劳动法_50"]))
    ok("社保被迫离职仍落到 38 条（新规则没吞掉老规则）",
       "劳动合同法_38" in rule_ids(
           "公司不缴社保我被迫离职，能不能要经济补偿",
           ["劳动合同法_38", "劳动合同法_46"]))
    ok("到期不续签落到 46 条",
       "劳动合同法_46" in rule_ids(
           "已经连续签了两次固定期限合同，公司到期不续签怎么办",
           ["劳动合同法_14", "劳动合同法_46"]))

